function travelTime(a, b) {
  if (!a || !b || a === b) return 0;
  const A = LOC[a], B = LOC[b];
  if (!A || !B) return 3;
  let t = 1 + (Math.abs(A.x - B.x) + Math.abs(A.y - B.y)) * 0.45;
  if ((A.zone === 'priem') !== (B.zone === 'priem')) t += 5; // лифт
  return Math.max(1, Math.round(t));
}

